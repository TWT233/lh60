@dataclass(frozen=True)
class LegacyConnectorCandidate:
    """One pose from the superseded bounded legacy-centroid search."""

    reference: str
    pin_count: int
    x_mm: float
    y_mm: float
    rotation_deg: float

    def __post_init__(self) -> None:
        if self.reference not in LEGACY_CONNECTOR_REFERENCES:
            raise ValueError(f"unexpected legacy connector reference: {self.reference}")
        if self.pin_count != CONNECTOR_PIN_COUNTS[self.reference]:
            raise ValueError(f"unexpected pin count for {self.reference}")
        if not all(
            math.isfinite(value)
            for value in (self.x_mm, self.y_mm, self.rotation_deg)
        ):
            raise ValueError("legacy connector candidate coordinates must be finite")
        if self.rotation_deg not in CANDIDATE_ROTATIONS_DEG:
            raise ValueError("legacy connector candidate rotation must be a quarter turn")

    def access_envelope(self) -> AxisAlignedRect:
        half_width = 2.54 / 2.0 + 1.0
        pin1_end = 2.54 / 2.0 + 1.0
        far_end = (self.pin_count - 1) * 2.54 + pin1_end

        if self.rotation_deg == 0.0:
            local_bounds = (-half_width, -far_end, half_width, pin1_end)
        elif self.rotation_deg == 90.0:
            local_bounds = (-pin1_end, -half_width, far_end, half_width)
        elif self.rotation_deg == 180.0:
            local_bounds = (-half_width, -pin1_end, half_width, far_end)
        else:
            local_bounds = (-far_end, -half_width, pin1_end, half_width)

        min_x, min_y, max_x, max_y = local_bounds
        return AxisAlignedRect(
            min_x=self.x_mm + min_x,
            min_y=self.y_mm + min_y,
            max_x=self.x_mm + max_x,
            max_y=self.y_mm + max_y,
        )


