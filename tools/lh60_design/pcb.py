def read_legacy_connector_centroids(
    path: Path | str = LEGACY_CONNECTOR_BASELINE,
) -> dict[str, tuple[float, float]]:
    payload = json.loads(Path(path).read_text())
    centroids = payload.get("centroids")
    if not isinstance(centroids, dict):
        raise ValueError("legacy connector baseline is missing centroids")
    if set(centroids) != set(LEGACY_CONNECTOR_REFERENCES):
        raise ValueError("legacy connector centroid references do not match J1..J6")

    result = {}
    for reference in LEGACY_CONNECTOR_REFERENCES:
        centroid = centroids[reference]
        if not isinstance(centroid, dict):
            raise ValueError(f"legacy connector centroid for {reference} is malformed")
        x_mm = centroid.get("x")
        y_mm = centroid.get("y")
        if (
            isinstance(x_mm, bool)
            or isinstance(y_mm, bool)
            or not isinstance(x_mm, (int, float))
            or not isinstance(y_mm, (int, float))
            or not math.isfinite(x_mm)
            or not math.isfinite(y_mm)
        ):
            raise ValueError(f"legacy connector centroid for {reference} is not finite")
        result[reference] = (float(x_mm), float(y_mm))
    return result


def _board_access_rejection_reasons(envelope: AxisAlignedRect) -> tuple[str, ...]:
    min_x = BOARD_ACCESS_MARGIN_MM
    min_y = BOARD_ACCESS_MARGIN_MM
    max_x = BOARD_WIDTH_MM - BOARD_ACCESS_MARGIN_MM
    max_y = BOARD_HEIGHT_MM - BOARD_ACCESS_MARGIN_MM
    reasons = []
    if envelope.min_x < min_x:
        reasons.append("board_min_x")
    if envelope.min_y < min_y:
        reasons.append("board_min_y")
    if envelope.max_x > max_x:
        reasons.append("board_max_x")
    if envelope.max_y > max_y:
        reasons.append("board_max_y")
    return tuple(reasons)


def _geometry_for_rect(rect: AxisAlignedRect):
    return box(rect.min_x, rect.min_y, rect.max_x, rect.max_y)


@lru_cache(maxsize=1)
def _socket_courtyard_geometries() -> tuple[tuple[str, object], ...]:
    specs = {spec.name: spec for spec in build_footprint_specs()}
    geometries = []
    keys_by_id = {key.physical_key_id: key for key in physical_keys()}
    for placement in socket_placement_plan():
        key = keys_by_id[placement.physical_key_id]
        footprint = _switch_footprint(key)
        footprint_name = re.sub(r"^[^:]+:", "", footprint)
        geometry = _courtyard_geometry(specs[footprint_name])
        geometry = affinity.rotate(
            geometry,
            -placement.rotation_deg,
            origin=(0, 0),
        )
        geometry = affinity.translate(
            geometry,
            xoff=placement.x_mm,
            yoff=placement.y_mm,
        )
        geometries.append((placement.reference, geometry))
    return tuple(geometries)


def audit_legacy_connector_search(
    centroids: Mapping[str, tuple[float, float]],
) -> tuple[LegacyPlacementAudit, ...]:
    """Replay the planned search through its first pure board-bound gate."""

    if set(centroids) != set(LEGACY_CONNECTOR_REFERENCES):
        raise ValueError("legacy connector centroid references do not match J1..J6")

    results = []
    for reference in LEGACY_CONNECTOR_REFERENCES:
        centroid_x, centroid_y = centroids[reference]
        if not all(
            isinstance(value, (int, float))
            and not isinstance(value, bool)
            and math.isfinite(value)
            for value in (centroid_x, centroid_y)
        ):
            raise ValueError(f"legacy connector centroid for {reference} is not finite")
        for offset_x, offset_y in CANDIDATE_OFFSETS_MM:
            for rotation in CANDIDATE_ROTATIONS_DEG:
                placement = LegacyConnectorCandidate(
                    reference=reference,
                    pin_count=CONNECTOR_PIN_COUNTS[reference],
                    x_mm=float(centroid_x + offset_x),
                    y_mm=float(centroid_y + offset_y),
                    rotation_deg=rotation,
                )
                envelope = placement.access_envelope()
                results.append(
                    LegacyPlacementAudit(
                        placement=placement,
                        offset_x_mm=offset_x,
                        offset_y_mm=offset_y,
                        envelope=envelope,
                        rejection_reasons=_board_access_rejection_reasons(envelope),
                    )
                )
    return tuple(results)


