def _default_passive_ffc_candidates() -> tuple[PassiveFfcPlacement, ...]:
    candidates = [
        PASSIVE_FFC_CANDIDATES[0],
        *_top_edge_passive_ffc_candidates(),
        *PASSIVE_FFC_CANDIDATES[1:],
        *_edge_passive_ffc_candidates(),
        *_former_mcu_region_passive_ffc_candidates(),
    ]
    deduplicated = []
    seen = set()
    for candidate in candidates:
        key = (
            candidate.reference,
            round(candidate.x_mm, 6),
            round(candidate.y_mm, 6),
            round(candidate.rotation_deg, 6),
            candidate.layer,
        )
        if key in seen:
            continue
        seen.add(key)
        deduplicated.append(candidate)
    return tuple(deduplicated)


def audit_passive_ffc_candidates(
    candidates: tuple[PassiveFfcPlacement, ...] | None = None,
) -> tuple[PassiveFfcCandidateAudit, ...]:
    candidates = _default_passive_ffc_candidates() if candidates is None else candidates
    audits = []
    socket_courtyards = _socket_courtyard_geometries()
    for candidate in candidates:
        reasons = []
        candidate_courtyard = candidate.courtyard_envelope()
        candidate_courtyard_geometry = _geometry_for_rect(candidate_courtyard)
        candidate_access_geometry = _geometry_for_rect(candidate.access_envelope())
        if candidate.courtyard_envelope().distance_to(candidate.access_envelope()) > 0:
            reasons.append("access_envelope_detached")
        for label, envelope in (
            ("body", candidate.body_envelope()),
            ("courtyard", candidate_courtyard),
            ("access", candidate.access_envelope()),
        ):
            reasons.extend(f"{label}_{reason}" for reason in _board_access_rejection_reasons(envelope))
        for reference, socket_courtyard in socket_courtyards:
            if candidate_courtyard_geometry.intersects(socket_courtyard):
                reasons.append(f"courtyard_collision_{reference}")
            if candidate_access_geometry.intersects(socket_courtyard):
                reasons.append(f"access_collision_{reference}")
        if candidate.copper_to_edge_mm < BOARD_ACCESS_MARGIN_MM:
            reasons.append("copper_to_edge")
        if candidate.first_bend_clearance_mm < candidate.stiffener_insertion_mm:
            reasons.append("first_bend_inside_stiffener")
        audits.append(PassiveFfcCandidateAudit(candidate, tuple(reasons)))
    return tuple(audits)


def selected_passive_ffc_candidate() -> PassiveFfcPlacement:
    for audit in audit_passive_ffc_candidates():
        if audit.viable:
            return audit.placement
    raise RuntimeError("no passive FFC placement candidate passed the bounded search")


def apply_passive_ffc_placement(
    client: McpClient,
    board: Path | str = BOARD,
) -> tuple[dict[str, object], ...]:
    board_path = str(board)
    schemas = client.tool_schemas("pcb_components")
    if "flip_component" not in schemas:
        raise RuntimeError("Konnect pcb_components is missing required tool: flip_component")
    if "set_component_placements" not in schemas:
        raise RuntimeError("Konnect pcb_components is missing required tool: set_component_placements")

    placement = selected_passive_ffc_candidate()
    flip_result = client.call_tool_json(
        "flip_component",
        {
            "board": board_path,
            "reference": placement.reference,
            "layer": placement.layer,
        },
    )
    if flip_result.get("reference") not in {None, placement.reference}:
        raise RuntimeError("passive FFC flip reference mismatch")
    if flip_result.get("layer") not in {None, placement.layer}:
        raise RuntimeError("passive FFC flip layer mismatch")
    requested = [
        {
            "reference": placement.reference,
            "x": placement.x_mm,
            "y": placement.y_mm,
            "rotation": placement.rotation_deg,
        }
    ]
    result = client.call_tool_json(
        "set_component_placements",
        {"board": board_path, "placements": requested},
    )
    placements = result.get("placements")
    if not isinstance(placements, list) or len(placements) != 1:
        raise RuntimeError("passive FFC placement evidence must contain one item")
    item = placements[0]
    if not isinstance(item, dict) or item.get("reference") != "J1":
        raise RuntimeError("passive FFC placement reference mismatch")
    for field, expected in requested[0].items():
        if field == "reference":
            continue
        if not _matches_finite_numeric_evidence(item.get(field), expected):
            raise RuntimeError(f"passive FFC placement {field} mismatch")
    return ({**requested[0], "layer": placement.layer, "flip": flip_result},)


def _balanced_block(source: str, start: int) -> tuple[int, int]:
    depth = 0
    in_string = False
    escaped = False
    for index in range(start, len(source)):
        character = source[index]
        if escaped:
            escaped = False
        elif in_string:
            if character == "\\":
                escaped = True
            elif character == '"':
                in_string = False
        elif character == '"':
            in_string = True
        elif character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
            if depth == 0:
                return start, index + 1
    raise ValueError(f"unbalanced S-expression starting at byte {start}")


def _direct_footprint_blocks(source: str) -> tuple[str, ...]:
    blocks = []
    depth = 0
    in_string = False
    escaped = False
    index = 0
    while index < len(source):
        character = source[index]
        if escaped:
            escaped = False
        elif in_string:
            if character == "\\":
                escaped = True
            elif character == '"':
                in_string = False
        elif character == '"':
            in_string = True
        elif character == "(":
            if depth == 1 and source.startswith("(footprint", index):
                start, end = _balanced_block(source, index)
                blocks.append(source[start:end])
                index = end
                continue
            depth += 1
        elif character == ")":
            depth -= 1
        index += 1
    return tuple(blocks)


def _root_tag_block(source: str, tag: str) -> str:
    marker = f"({tag}"
    for start in range(len(source)):
        if not source.startswith(marker, start):
            continue
        prefix = source[start + len(marker) : start + len(marker) + 1]
        if prefix not in {" ", "\t", "\r", "\n", ")"}:
            continue
        depth = 0
        in_string = False
        escaped = False
        for index, character in enumerate(source[:start]):
            if escaped:
                escaped = False
            elif in_string:
                if character == "\\":
                    escaped = True
                elif character == '"':
                    in_string = False
            elif character == '"':
                in_string = True
            elif character == "(":
                depth += 1
            elif character == ")":
                depth -= 1
        if depth == 1:
            block_start, block_end = _balanced_block(source, start)
            return source[block_start:block_end]
    raise ValueError(f"missing root ({tag} ...) block")


def read_board_placements(
    board: Path | str = BOARD,
) -> dict[str, tuple[float, float, float, str]]:
    source = Path(board).read_text()
    placements = {}
    for block in _direct_footprint_blocks(source):
        reference_marker = '(property "Reference" "'
        reference_start = block.find(reference_marker)
        if reference_start < 0:
            continue
        reference_start += len(reference_marker)
        reference_end = block.find('"', reference_start)
        reference = block[reference_start:reference_end]
        at_tokens = _root_tag_block(block, "at")[1:-1].split()
        layer_block = _root_tag_block(block, "layer")
        layer = layer_block.split('"', 2)[1]
        placements[reference] = (
            float(at_tokens[1]),
            float(at_tokens[2]),
            float(at_tokens[3]) if len(at_tokens) > 3 else 0.0,
            layer,
        )
    return placements


def _region_rotations() -> dict[str, float]:
    rotations: dict[str, float] = {}
    for report_path in sorted(REGION_REPORTS.glob("*.json")):
        report = json.loads(report_path.read_text())
        for placement in report["placements"]:
            physical_key_id = placement["socket_ref"]
            if physical_key_id in rotations:
                raise ValueError(
                    f"duplicate regional placement for {physical_key_id}"
                )
            rotations[physical_key_id] = float(placement["rotation_deg"])
    return rotations


def socket_placement_plan() -> tuple[FootprintPlacement, ...]:
    references = switch_references()
    rotations = _region_rotations()
    rotations.update(REVIEWED_ROTATION_OVERRIDES_DEG)
    keys = physical_keys()
    regional_key_ids = {
        key.physical_key_id for key in keys if key.region is not None
    }
    if set(rotations) != regional_key_ids:
        missing = sorted(regional_key_ids - set(rotations))
        extra = sorted(set(rotations) - regional_key_ids)
        raise ValueError(
            f"regional placement reports do not match layout: missing={missing}, extra={extra}"
        )

    return tuple(
        FootprintPlacement(
            physical_key_id=key.physical_key_id,
            reference=references[key.physical_key_id],
            x_mm=key.center_x_mm,
            y_mm=key.center_y_mm,
            rotation_deg=rotations.get(key.physical_key_id, 0.0),
        )
        for key in keys
    )


def apply_socket_placements(client: McpClient, board: Path | str = BOARD) -> None:
    board_path = str(board)
    schemas = client.tool_schemas("pcb_components")
    missing = {"move_component", "rotate_component"} - set(schemas)
    if missing:
        raise RuntimeError(
            f"Konnect pcb_components is missing required tools: {sorted(missing)}"
        )
    for placement in socket_placement_plan():
        client.call_tool(
            "move_component",
            {
                "board": board_path,
                "reference": placement.reference,
                "x": placement.x_mm,
                "y": placement.y_mm,
            },
        )
        client.call_tool(
            "rotate_component",
            {
                "board": board_path,
                "reference": placement.reference,
                "rotation": placement.rotation_deg,
            },
        )


_BATCH_SET_COMPONENT_POSES_SCHEMA = {
    "additionalProperties": False,
    "properties": {
        "board": {"type": "string"},
        "placements": {
            "items": {
                "additionalProperties": False,
                "properties": {
                    "layer": {
                        "enum": ["F.Cu", "B.Cu"],
                        "type": "string",
                    },
                    "reference": {"type": "string"},
                    "rotation": {"type": "number"},
                    "x": {"type": "number"},
                    "y": {"type": "number"},
                },
                "required": ["reference", "x", "y", "rotation", "layer"],
                "type": "object",
            },
            "type": "array",
        },
    },
    "required": ["board", "placements"],
    "type": "object",
}


def _matches_finite_numeric_evidence(value: object, expected: float) -> bool:
    return (
        type(value) in (int, float)
        and math.isfinite(value)
        and value == expected
    )


def apply_connector_placements(
    client: McpClient,
    board: Path | str = BOARD,
) -> tuple[dict[str, object], ...]:
    board_path = str(board)
    schemas = client.tool_schemas("pcb_components")
    schema = schemas.get("batch_set_component_poses")
    if schema is None:
        raise RuntimeError(
            "Konnect pcb_components is missing required tool: "
            "batch_set_component_poses"
        )
    if schema != _BATCH_SET_COMPONENT_POSES_SCHEMA:
        raise RuntimeError("batch_set_component_poses schema mismatch")

    plan = frozen_connector_placements()
    requested = [
        {
            "reference": placement.reference,
            "x": placement.x_mm,
            "y": placement.y_mm,
            "rotation": placement.rotation_deg,
            "layer": placement.layer,
        }
        for placement in plan
    ]
    result = client.call_tool_json(
        "batch_set_component_poses",
        {"board": board_path, "placements": requested},
    )

    changed = result.get("changed")
    updated_count = result.get("updated_count")
    placements = result.get("placements")
    if result.get("source") != "file":
        raise RuntimeError("atomic connector placement must use the file source")
    if result.get("atomic") is not True:
        raise RuntimeError("atomic connector placement did not prove atomic=true")
    if not isinstance(changed, bool):
        raise RuntimeError("atomic connector placement changed must be bool")
    if isinstance(updated_count, bool) or not isinstance(updated_count, int):
        raise RuntimeError("atomic connector placement updated_count must be int")
    if not isinstance(placements, list) or len(placements) != len(plan):
        raise RuntimeError("atomic connector placement evidence must contain six items")

    evidence = []
    references = []
    changed_count = 0
    for expected, item in zip(requested, placements):
        if not isinstance(item, dict):
            raise RuntimeError("atomic connector placement item must be an object")
        item_changed = item.get("changed")
        if not isinstance(item_changed, bool):
            raise RuntimeError("atomic connector placement item changed must be bool")
        references.append(item.get("reference"))
        if (
            item.get("reference") != expected["reference"]
            or item.get("layer") != expected["layer"]
            or any(
                not _matches_finite_numeric_evidence(
                    item.get(field),
                    expected[field],
                )
                for field in ("x", "y", "rotation")
            )
        ):
            raise RuntimeError("atomic connector placement pose evidence mismatch")
        changed_count += int(item_changed)
        evidence.append({**expected, "changed": item_changed})

    expected_references = [placement.reference for placement in plan]
    if len(set(references)) != len(references) or references != expected_references:
        raise RuntimeError("atomic connector placement references mismatch")
    if updated_count != changed_count:
        raise RuntimeError("atomic connector placement updated_count mismatch")
    if changed is not (updated_count > 0):
        raise RuntimeError("atomic connector placement changed/count mismatch")
    return tuple(evidence)


